// Species-name -> staged slug. Roster resolutions (Mars 2026-10-26):
// 003 = AquariiOS (hyphen out) and 005 = Chromejaww, with Chromedile as
// the old name for Chromejaww — so the in-code spellings "Aquari-OS"
// and "Chromedile" both map to their staged slugs below. Every other
// in-game species slug matches its staged file exactly.
const SPECIES_SLUG_ALIASES: Record<string, string> = { aquarios: 'aquariios', chromedile: 'chromejaww' };

export function speciesSlug(name: string | undefined): string | null {
  if (!name) return null;
  const slug = name.toLowerCase().replace(/[^a-z0-9]/g, '');
  return SPECIES_SLUG_ALIASES[slug] || slug;
}

export function lustreFrontForSpecies(name: string | undefined): string | null {
  const slug = speciesSlug(name);
  if (!slug || !LUSTRE_FRONT_SLUGS.includes(slug)) return null;
  return `/assets/variants/lustre/${slug}_lustre_front.png`;
}

