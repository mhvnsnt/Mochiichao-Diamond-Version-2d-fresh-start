/**
 * Lustre variants — the Pokemon shiny system, under Mars's locked in-game
 * name LUSTRE (Mars 2026-10-26 ~14:31 CDT; production conversation may
 * still say "shiny", no player-facing string says "shiny").
 *
 * Pokemon baseline (FireRed first, then HeartGold / Black 2 same structure):
 * - Determination: shinyValue = HI(otId) ^ LO(otId) ^ HI(personality) ^
 *   LO(personality); a creature is shiny when shinyValue < SHINY_ODDS (8),
 *   i.e. 8/65536 = 1/8192 (pokefirered-leafgreen include/constants/pokemon.h
 *   + src/battle_anim_special.c TryShinyAnimation; battle entry also plays
 *   a sparkle animation for shiny creatures).
 * - Mechanism: a per-species alternate palette table (gMonShinyPalette_*,
 *   shiny_palette_table.h) swapped in for the shiny creature.
 *
 * Mochiichao mapping — 10 Lustre variants per creature (Mars 2026-10-26
 * ~14:31 CDT: 10, NOT just Solar/Lunar/Prism; palette-only is NOT the
 * system — variants are colorways, outfits and looks):
 * - Slots approved by Mars 2026-10-26 ~14:54 CDT: Solar, Lunar, Prism,
 *   Bare, Clothed, Showtime, Iron, Ember, Night, Parade.
 * - Determination: the Pokemon XOR value < 8 gives any Lustre
 *   (8/65536 = 1/8192); the slot is (otId XOR personality) mod 10,
 *   so each slot is 1/81920.
 * - Art wired now: the staged shiny-v2 palette + front per creature
 *   (51/51 sets) is the SOLAR look. The other nine variants render
 *   through their look descriptor + a distinct hue filter on the Solar
 *   front until per-variant outfit/look art lands — that art is owed,
 *   not faked as finished.
 *
 * This game has no personality / OT-ID fields on a creature instance yet,
 * so lustreVariantFor() feeds a stable hash of the instance id through the
 * exact same XOR-threshold function. When personality/OT fields land, call
 * determineLustreVariant(otId, personality) directly and delete the hash
 * surrogate — the bands and labels do not change.
 */
export type LustreVariantId =
  | 'solar' | 'lunar' | 'prism' | 'bare' | 'clothed'
  | 'showtime' | 'iron' | 'ember' | 'night' | 'parade';
export type CoatVariant = 'standard' | LustreVariantId;

export interface LustreVariantDef {
  id: LustreVariantId;
  label: string;
  look: string;
  hueRotateDeg: number; // provisional render filter until outfit/look art lands
}

