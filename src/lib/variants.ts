export const LUSTRE_THRESHOLD = 8; // 8/65536 = 1/8192 any Lustre, FireRed SHINY_ODDS
export const LUSTRE_ANY_ODDS = '1 in 8,192';
export const LUSTRE_VARIANT_ODDS = '1 in 81,920';

export function variantValue(otId: number, personality: number): number {
  return (((otId >>> 16) ^ (otId & 0xffff) ^ (personality >>> 16) ^ (personality & 0xffff)) & 0xffff);
}

// Any-Lustre keeps the exact Pokemon rule (XOR value < 8). The slot is
// then the second value (otId XOR personality) mod 10, so each slot is
// (8/65536) x (1/10) = 1/81920, matching the approved rates.
export function determineLustreVariant(otId: number, personality: number): CoatVariant {
  if (variantValue(otId, personality) >= LUSTRE_THRESHOLD) return 'standard';
  return LUSTRE_VARIANTS[((otId ^ personality) >>> 0) % LUSTRE_VARIANTS.length].id;
}

function fnv1a(text: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < text.length; i++) {
    h ^= text.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h >>> 0;
}

export function coatVariantFor(instanceId: string): CoatVariant {
  return determineLustreVariant(fnv1a(instanceId), fnv1a(instanceId + ':coat'));
}
export const lustreVariantFor = coatVariantFor;

export function lustreDef(variant: CoatVariant): LustreVariantDef | null {
  return variant === 'standard' ? null : (LUSTRE_VARIANTS.find(d => d.id === variant) || null);
}

export function coatLabel(coat: CoatVariant): string {
  if (coat === 'standard') return 'Standard coat';
  return lustreDef(coat)?.label || 'Standard coat';
}

export function coatLook(coat: CoatVariant): string {
  return lustreDef(coat)?.look || '';
}

