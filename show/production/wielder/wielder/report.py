"""WIELDER review packet — generated from artifacts only (Constitution
#8; Counter-addition #1: evidence-only status). Every line is bound to a
ledger row, a tool result, the provenance lock, or the verifier
manifest. The packet's headline is the self-judgment core result —
failures first, never a side-metric. The finished packet passes the
claim linter before it is written; a packet that cannot be linted is
not emitted.
"""
from __future__ import annotations

import json
from pathlib import Path

from . import constitution as C
from . import judgment as judgment_mod
from . import linter
from .ledger import Ledger


def build_packet(ledger: Ledger, run_id: str) -> Path:
    run = ledger.get_run(run_id)
    out_dir = C.DATA / "runs" / run_id
    out_dir.mkdir(parents=True, exist_ok=True)
    manifest = None
    if run["manifest_path"] and Path(run["manifest_path"]).exists():
        manifest = json.loads(Path(run["manifest_path"]).read_text())
    lines = [f"# WIELDER run packet — {run_id}", ""]
    if manifest is not None:
        lines += [judgment_mod.headline(manifest), ""]
    lines += [
        f"- Card: #{run['card_id']} — {run['card_title']}",
        f"- Target: {run['target_id']}",
        f"- Final run state (ledger): {run['state']}",
        f"- Blocker: {run['blocker'] or 'none recorded'}",
        f"- Verifier manifest: {run['manifest_path'] or 'NONE — no manifest exists for this run'}",
        f"- Manifest sha256: {run['manifest_sha256'] or 'none'}",
        "",
        "## Input provenance lock (inputs + sha256 recorded at run start)",
    ]
    for i in run.get("inputs", []):
        lines.append(f"- {i['kind']}: {i['path']} — sha256 {i['sha256']} ({i['bytes']} bytes)")
    lines += ["", "## State transitions (ledger)"]
    for t in run["transitions"]:
        lines.append(f"- {t['ts']} {t['from'] or '∅'} → {t['to']}: {t['reason']}")
    lines += ["", "## Tool calls (execution layer, exit codes unedited)"]
    for tc in run["tool_calls"]:
        lines.append(f"- {tc['ts']} {tc['tool']} ok={bool(tc['ok'])} exit={tc['exit_code']}")
    # Proof gate (owner expansion): the packet carries the evidence
    # bundle itself — each artifact hash-bound — or names what is
    # missing. Generated from the ledger's tool rows, never claimed.
    try:
        from . import evidence as _ev
        rep = _ev.check(_ev.from_ledger_rows(run["tool_calls"]), run["target_id"])
        lines += ["", "## Evidence bundle (proof gate)"]
        for b in rep["bundle"]:
            lines.append(f"- {b['kind']}: {b['ref']} — sha256 {b['sha256']} ({b['detail']})")
        if rep["missing"]:
            lines.append("- Missing evidence: " + "; ".join(rep["missing"]))
        elif rep["bundle"]:
            lines.append("- Every required evidence class is present above, hash-bound.")
    except Exception as e:
        lines += ["", "## Evidence bundle (proof gate)", f"- unavailable: {e}"]
    sj = out_dir / "self_judgment.md"
    if sj.exists():
        lines += ["", sj.read_text().strip()]
    elif manifest is not None:
        lines += ["", judgment_mod.judgment_section(manifest)]
    lines += ["", "Generated by wielder.report from the run ledger + verifier manifest. "
                  "Status lines are generated from measurements; no status in this "
                  "packet originates from a model or a worker claim."]
    text = "\n".join(lines) + "\n"
    linter.lint(text)  # claim-lint gate: raises rather than emit a bad packet
    packet = out_dir / "packet.md"
    packet.write_text(text)
    return packet
